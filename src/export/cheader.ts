// C header for game integration (pairs with the replayer in src/export/replayer.ts).

function words(data: Uint8Array): string[] {
  const out: string[] = [];
  for (let i = 0; i < data.length; i += 16) {
    const row: string[] = [];
    for (let k = i; k < Math.min(i + 16, data.length); k += 2) row.push('0x' + (((data[k] << 8) | (data[k + 1] ?? 0)) >>> 0).toString(16).padStart(4, '0'));
    out.push('    ' + row.join(',') + ',');
  }
  return out;
}

/** `drumTable` = output of packDrumTable (digidrum samples used by the stream), if the song has any */
export function writeCHeader(name: string, data: Uint8Array, nframes: number, loopFrame: number, loopOffset: number, drumTable?: Uint8Array | null): string {
  const N = name.toUpperCase().replace(/[^A-Z0-9_]/g, '_');
  const n = name.toLowerCase().replace(/[^a-z0-9_]/g, '_');
  const lines = [
    `/* generated by MOD/XM -> YM tool - ${nframes} frames @ 50 Hz, ${data.length} bytes${drumTable ? `, digidrum table ${drumTable.length} bytes` : ''} */`,
    `#define ${N}_FRAMES ${nframes}`,
    `#define ${N}_LOOP_FRAME ${loopFrame}`,
    `#define ${N}_LOOP_OFFSET ${loopOffset}`,
    `static const unsigned char ${n}_data[${data.length}] = {`,
  ];
  for (let i = 0; i < data.length; i += 24) lines.push('    ' + Array.from(data.subarray(i, i + 24)).join(',') + ',');
  lines.push('};');
  if (drumTable) {
    const cnt = (drumTable[0] << 8) | drumTable[1];
    lines.push(`#define ${N}_DRUMS ${cnt}`, `/* digidrum samples: pass to ymdrum_init() (word aligned, so keep it as unsigned short) */`,
      `static const unsigned short ${n}_drums[${(drumTable.length + 1) >> 1}] = {`, ...words(drumTable), '};');
  }
  return lines.join('\n') + '\n';
}
