#!/bin/sh
# Assemble the SNDH player (player.s, includes drumeng.s) and the stand-alone game drum engine (gamedrum.s)
# into flat blobs and emit src/player68k/blob.ts.
set -e
cd "$(dirname "$0")"
AS=${AS:-m68k-linux-gnu-as}; OBJCOPY=${OBJCOPY:-m68k-linux-gnu-objcopy}; NM=${NM:-m68k-linux-gnu-nm}
for f in player gamedrum; do
  $AS -m68000 --register-prefix-optional -o $f.o $f.s
  $OBJCOPY -O binary -j .text $f.o $f.bin
done
$NM gamedrum.o > gamedrum.sym
python3 - <<'PY'
import re
b = open('player.bin','rb').read()
g = open('gamedrum.bin','rb').read()
sym = {m[2]: int(m[1],16) for m in (re.match(r'([0-9a-f]+) \w (\w+)', l) for l in open('gamedrum.sym')) if m}
print('player blob', len(b), 'bytes; game drum blob', len(g), 'bytes')
def arr(x): return ",".join(str(v) for v in x)
open('blob.ts','w').write("// generated by build.sh from player.s / gamedrum.s - do not edit\n"
  "export const PLAYER_BLOB = Uint8Array.from([\n" + arr(b) + "]);\n"
  "export const GAME_DRUM_BLOB = Uint8Array.from([\n" + arr(g) + "]);\n"
  "/** byte offsets inside GAME_DRUM_BLOB */\n"
  "export const GAME_DRUM_OFFSETS = { init: 0, exit: 4, start: 8, stop: 12, tab: %d, voice: %d, idx: %d, sel: %d, act: %d } as const;\n"
  % (sym['g_tab'], sym['g_voice'], sym['g_idx'], sym['dv_sel'], sym['dv_act']))
PY
rm -f player.o gamedrum.o gamedrum.sym
