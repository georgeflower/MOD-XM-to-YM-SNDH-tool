#!/bin/sh
# Assemble the SNDH player into a flat blob and emit src/player68k/blob.ts.
set -e
cd "$(dirname "$0")"
AS=${AS:-m68k-linux-gnu-as}; OBJCOPY=${OBJCOPY:-m68k-linux-gnu-objcopy}
$AS -m68000 --register-prefix-optional -o player.o player.s
$OBJCOPY -O binary -j .text player.o player.bin
python3 - <<'PY'
b = open('player.bin','rb').read()
print('player blob', len(b), 'bytes')
open('blob.ts','w').write("// generated by build.sh from player.s - do not edit\nexport const PLAYER_BLOB = Uint8Array.from([\n" +
  ",".join(str(x) for x in b) + "]);\n")
PY
rm -f player.o
